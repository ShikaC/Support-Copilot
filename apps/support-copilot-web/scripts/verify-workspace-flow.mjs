import { chromium } from 'playwright-core'
import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../docs/enterprise-workspace/screenshots')
const baseUrl = process.env.SUPPORT_WORKSPACE_URL ?? 'http://127.0.0.1:18173'
if (!['127.0.0.1', 'localhost'].includes(new URL(baseUrl).hostname)) throw new Error('Only a local synthetic-data workspace is allowed.')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({viewport:{width:1600,height:1000},reducedMotion:'reduce'})
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const title = `账单核验 · 工作台验收 ${Date.now()}`
const note = '已核对合成交易记录，等待财务复核。内部备注不发给客户。'
try {
  await page.goto(baseUrl)
  await page.getByText('业务 API 已连接').waitFor()
  await page.getByRole('button', { name:'＋ 新建工单',exact:true }).click()
  await page.getByLabel('工单标题',{exact:true}).fill(title)
  await page.getByLabel('联系人',{exact:true}).fill('验收客户')
  await page.getByLabel('客户企业',{exact:true}).fill('合成验收企业')
  await page.getByLabel('问题描述',{exact:true}).fill('同一订单出现重复扣款，请核验账单流水，并保留人工复核记录。')
  await page.screenshot({path:path.join(output,'create-ticket.png')})
  const creation = page.waitForResponse(response => response.url().endsWith('/commands/create') && response.request().method() === 'POST')
  await page.getByRole('button',{name:'创建工单',exact:true}).click()
  const createdResponse = await creation
  assert.equal(createdResponse.status(),201)
  const created = await createdResponse.json()
  await page.getByRole('heading',{name:title,exact:true}).waitFor()
  await page.getByRole('button',{name:'领取工单',exact:true}).click()
  await page.getByText('匿名演示操作人',{exact:true}).waitFor()
  await page.getByRole('button',{name:'编辑属性',exact:true}).click()
  await page.getByLabel('负责人',{exact:true}).fill('财务协作组')
  await page.getByRole('button',{name:'保存修改',exact:true}).click()
  await page.getByText('财务协作组',{exact:true}).waitFor()
  await page.getByRole('button',{name:'开始处理',exact:true}).click()
  await page.getByRole('button',{name:'标记为已解决',exact:true}).waitFor()
  await page.getByRole('textbox',{name:'添加内部备注'}).fill(note)
  await page.getByRole('button',{name:'保存备注',exact:true}).click()
  await page.getByText(note,{exact:true}).waitFor()
  await page.getByRole('button',{name:'开始分析',exact:true}).click()
  await page.getByRole('button',{name:'重新分析',exact:true}).waitFor({timeout:125000})
  await page.getByRole('tab',{name:'回复建议',exact:true}).click()
  await page.screenshot({path:path.join(output,'review-reply.png'),fullPage:true})
  await page.getByRole('button',{name:'记录审核',exact:true}).click()
  await page.getByRole('button',{name:'审核已记录',exact:true}).waitFor()
  await page.screenshot({path:path.join(output,'review-saved.png'),fullPage:true})
  await page.reload()
  await page.getByRole('button',{name:new RegExp(title.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).click()
  await page.getByText(note,{exact:true}).waitFor()
  let response = await page.request.get(`${baseUrl}/api/tickets/${created.id}`)
  let snapshot = await response.json()
  assert.equal(snapshot.latestReview.action,'APPROVED')
  assert.equal(snapshot.latestAnalysis.mode,'mock')
  assert.equal(snapshot.assigneeName,'财务协作组')
  const stale = await page.request.patch(`${baseUrl}/api/tickets/${created.id}`, {data:{priority:'URGENT',expectedVersion:created.version}})
  assert.equal(stale.status(),409)
  assert.equal((await stale.json()).code,'VERSION_CONFLICT')
  await page.getByRole('button',{name:'开始处理',exact:true}).click()
  await page.getByRole('button',{name:'标记为已解决',exact:true}).click()
  await page.getByRole('button',{name:/^确\s*认$/}).click()
  await page.getByRole('button',{name:'关闭工单',exact:true}).click()
  await page.getByRole('button',{name:/^确\s*认$/}).click()
  await page.getByText('该工单已完成处理',{exact:true}).waitFor()
  response = await page.request.get(`${baseUrl}/api/tickets/${created.id}`)
  snapshot = await response.json()
  assert.equal(snapshot.status,'CLOSED')
  const rejectedNote = await page.request.post(`${baseUrl}/api/tickets/${created.id}/notes`,{data:{noteId:randomUUID(),content:'关闭后的备注应被拒绝',expectedVersion:snapshot.version}})
  assert.equal(rejectedNote.status(),409)
  const events = await (await page.request.get(`${baseUrl}/api/audit-events?targetId=${created.id}&targetType=TICKET`)).json()
  assert(events.items.some(event => event.action === 'TICKET_NOTE_ADDED' && event.metadata.noteId))
  await page.screenshot({path:path.join(output,'closed-ticket.png'),fullPage:true})
  assert.deepEqual(errors,[])
  const result = {ticketId:created.id, mode:'real Java + real Python deterministic mock', create:true, trustedClaim:true, edit:true, notePersistenceAfterReload:true, analysis:true, review:true, resolvedAndClosed:true, staleWriteRejected:true, closedNoteRejected:true, auditEvents:events.items.length, browserErrors:errors}
  await fs.writeFile(path.join(output,'workflow-results.json'),JSON.stringify(result,null,2))
  console.log(JSON.stringify(result))
} catch (error) { await page.screenshot({path:path.join(output,'workflow-failure.png'),fullPage:true}); throw error } finally { await browser.close() }
